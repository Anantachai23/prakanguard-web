export function isWorkPcSession(s) {
  if (!s) return true;
  if (currentDeviceId && s.device_id === currentDeviceId) return true;
  if (currentSessionId && s.session_id === currentSessionId) return true;
  if (EXCLUDED_WORK_PC_SESSIONS.has(s.session_id)) return true;
  if (state && state.adminIp && s.ip && s.ip === state.adminIp && (s.device === 'PC' || s.device === 'Desktop' || (s.os && s.os.toLowerCase().includes('win')))) return true;
  if (s.ip === '171.96.89.22' && (s.device === 'PC' || s.device === 'Desktop' || (s.os && s.os.toLowerCase().includes('win')))) return true;
  // Any PC session generated by this admin machine's previous IDs or current machine
  if ((s.device === 'PC' || s.device === 'Desktop') && (s.device_id === currentDeviceId || EXCLUDED_WORK_PC_SESSIONS.has(s.session_id))) return true;
  // Ghost dev sessions left open for excessive hours (> 3 hours continuous ping on a PC)
  const lastPing = s.last_ping ? new Date(s.last_ping).getTime() : 0;
  const created = s.created_at ? new Date(s.created_at).getTime() : lastPing;
  const durMs = Math.max(0, lastPing - created);
  if ((s.device === 'PC' || s.device === 'Desktop' || !s.device) && durMs > 3 * 3600 * 1000) return true;
  return false;
}

// Asynchronously purge work PC sessions from Supabase table so database stays clean
async function purgeWorkPcSessionsFromDb(sessions) {
  try {
    const toDelete = sessions.filter(s => isWorkPcSession(s)).map(s => s.session_id);
    for (const sid of toDelete) {
      rest(`visitors?session_id=eq.${encodeURIComponent(sid)}`, { method: 'DELETE' }).catch(() => {});
    }
  } catch (e) {}
}

