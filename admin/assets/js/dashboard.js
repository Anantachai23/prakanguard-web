function updateReportsSelectionUI() {
  const count = state.selectedReports.size;
  const bar = $('#reports-batch-actions');
  const countLabel = $('#reports-selected-count');
  if (bar && countLabel) {
    if (count > 0) {
      bar.style.display = 'flex';
      countLabel.textContent = `เลือกแล้ว ${count} รายการ`;
    } else {
      bar.style.display = 'none';
    }
  }
  const thCheck = $('#th-reports-select-all');
  if (thCheck) {
    thCheck.checked = state.reports.length > 0 && count === state.reports.length;
    thCheck.indeterminate = count > 0 && count < state.reports.length;
  }
}

