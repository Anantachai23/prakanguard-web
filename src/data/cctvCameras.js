// Helper to filter cameras by district
export function getCamerasByDistrict(district) {
  if (!district || district === "ทั้งหมด") return CCTV_CAMERAS;
  return CCTV_CAMERAS.filter(c => c.district.includes(district) || district.includes(c.district));
}

// Helper to get camera by ID
export function getCameraById(id) {
  return CCTV_CAMERAS.find(c => c.id === id) || null;
}
