// ฟังก์ชันคำนวณคะแนนความตรงกันของการค้นหา (Relevance Score) เพื่อเรียงลำดับผลลัพธ์ที่ตรงที่สุดขึ้นก่อน
export function scoreLocationSearch(item, rawQuery) {
  if (!rawQuery) return 1;
  const qClean = rawQuery.trim().toLowerCase().replace(/\s+/g, '');
  if (!qClean) return 1;

  const cleanName = (item.name || '').toLowerCase().replace(/\s+/g, '');
  if (cleanName === qClean) return 100;
  if (cleanName.includes(qClean)) return 80;

  // 1. Direct alias match (เช่น ค้นหา "บางฉโลง" ตรงกับ alias "บางฉโลง")
  if (Array.isArray(item.aliases)) {
    for (const a of item.aliases) {
      const cleanA = a.toLowerCase().replace(/\s+/g, '');
      if (cleanA === qClean) return 95;
      if (cleanA.includes(qClean) || qClean.includes(cleanA)) return 75;
    }
  }

  // 2. Direct keyword match
  if (Array.isArray(item.keywords)) {
    for (const k of item.keywords) {
      const cleanK = k.toLowerCase().replace(/\s+/g, '');
      if (cleanK === qClean) return 90;
      if (cleanK.includes(qClean)) return 70;
    }
  }

  // 3. Colloquial & Typo Synonym match จากพจนานุกรมคำพ้อง
  for (const [key, synonyms] of Object.entries(COLLOQUIAL_SEARCH_MAP)) {
    const cleanKey = key.toLowerCase().replace(/\s+/g, '');
    if (qClean.includes(cleanKey) || cleanKey.includes(qClean)) {
      for (const syn of synonyms) {
        const cleanSyn = syn.toLowerCase().replace(/\s+/g, '');
        if (cleanName.includes(cleanSyn)) return 65;
        if (Array.isArray(item.aliases) && item.aliases.some(a => a.toLowerCase().replace(/\s+/g, '').includes(cleanSyn))) return 60;
        if (Array.isArray(item.keywords) && item.keywords.some(k => k.toLowerCase().replace(/\s+/g, '').includes(cleanSyn))) return 55;
      }
    }
  }

  // 4. Subdistrict / District match
  const cleanSub = (item.subdistrict || '').toLowerCase().replace(/\s+/g, '');
  const cleanDis = (item.district || '').toLowerCase().replace(/\s+/g, '');
  if (cleanSub.includes(qClean)) return 40;
  if (cleanDis.includes(qClean)) return 30;

  // 5. Other text (cause, trafficStatus)
  const cleanCause = (item.cause || '').toLowerCase().replace(/\s+/g, '');
  if (cleanCause.includes(qClean)) return 20;

  return 0;
}

// ฟังก์ชันค้นหาจุดเสี่ยงที่รองรับชื่อเรียกติดปาก, คำพ้องเสียง, คำสะกดผิด, และแลนด์มาร์ก (Smart Fuzzy Search)
export function matchesLocationSearch(item, rawQuery) {
  return scoreLocationSearch(item, rawQuery) > 0;
}

