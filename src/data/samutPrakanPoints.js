/**
 * ค้นหาแนวถนนน้ำท่วมขังต่อเนื่อง (Corridor) ที่จุดรายงานหรือพิกัดนี้สังกัดอยู่
 */
export function findCorridorForPoint(point) {
  if (!point) return null;
  
  // 1. ตรวจสอบโดยตรงจาก pointId
  const byPointId = MAJOR_FLOOD_CORRIDORS.find(c => c.pointIds && c.pointIds.includes(point.id));
  if (byPointId) return byPointId;

  // 2. ตรวจสอบจากชื่อถนนหรือคำสำคัญ
  const pName = (point.name || '').toLowerCase();
  const pDistrict = point.district || '';

  const matched = MAJOR_FLOOD_CORRIDORS.find(c => {
    if (c.district !== pDistrict && !c.coveredDistricts.includes(pDistrict)) return false;
    if (pName.includes('ศรีนครินทร์') && c.id === 'corridor-srinakarin') return true;
    if (pName.includes('สุขุมวิท') && c.id === 'corridor-sukhumvit') return true;
    if (pName.includes('เทพารักษ์') && c.id === 'corridor-theparak') return true;
    if ((pName.includes('บางนา') || pName.includes('หัวเฉียว') || pName.includes('บางโฉลง')) && c.id === 'corridor-bangna-trat') return true;
    if (pName.includes('กิ่งแก้ว') && c.id === 'corridor-kingkaeo') return true;
    if (pName.includes('ปู่เจ้า') && c.id === 'corridor-puchao') return true;
    if ((pName.includes('สุขสวัสดิ์') || pName.includes('พระสมุทรเจดีย์') || pName.includes('ป้อมพระจุล')) && c.id === 'corridor-suksawat') return true;
    if (pName.includes('แพรกษา') && c.id === 'corridor-phraeksa') return true;
    if ((pName.includes('บางบ่อ') || pName.includes('ปานวิถี') || pName.includes('คลองด่าน')) && c.id === 'corridor-panwithi') return true;
    if (pName.includes('ประชาอุทิศ') && c.id === 'corridor-prachauthit') return true;
    return false;
  });

  return matched || null;
}

